#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// refresh-readiness.mjs — the catalogue figures LAUNCH_READINESS.md and
// LAUNCH_PLAN.md state, computed rather than copied (backlog item 47, filed by
// item 39's scoping; extended to LAUNCH_PLAN.md by item 55).
//
// WHY THIS EXISTS. LAUNCH_READINESS.md's "How to refresh" section used to
// carry two `node -e '…'` snippets: code stored in prose. Nothing imported
// them, nothing ran them, and they rotted twice — once for three days after
// item 25 split lesson content per track, once for a few hours after item 45
// split it per language. Both times the snippets named a file that no longer
// existed and would have thrown ERR_MODULE_NOT_FOUND, while the figures
// printed *beside* them stayed correct. That is the shape of this project's
// recurring failure and it is worth stating plainly: the number was right and
// the method had rotted. Item 46's §26 check now catches a dead path inside
// such a snippet; this script removes the snippet instead, which kills the
// class rather than guarding it. A figure that is derived cannot go stale,
// and a procedure that runs on every `npm test` cannot name a missing file.
//
// THREE MODES, the `gofmt` shape:
//   (no args)   print the figures — what the deleted snippets did.
//   --check     compare them against what the documents state, and exit 1 on
//               disagreement. Chained into `npm test`.
//   --write     rewrite those figures in the documents in place.
//
// `--write` is not a convenience; it is what makes `--check` survivable.
// check-data.mjs §11b deliberately declined to guard character counts,
// reasoning that "a build that fails over 19 characters would be turned off
// within a week." That objection is correct about a hand-maintained figure
// and does not apply to a generated one: the fix here is one command, not a
// re-derivation, so the gate costs a run nothing to satisfy.
//
// SCOPE — every figure here is *live*: it must equal the content as it is
// today. The other ~119 measurement-shaped numbers in the four documents are
// history ("dropped to 93% earlier that day", "fell by exactly 19 characters")
// and must never change. No parser separates the two — see item 39's scoping —
// so the split is made by hand, here, and kept small.
//
// WHY LAUNCH_PLAN.md JOINED (item 55). The plan is the document that answers
// "is a gate cleared?", and on 2026-08-17 it answered wrong: §4.3 read "the
// gate is not close: 12 minutes is not 2 hours" while LAUNCH_READINESS.md —
// generated by this script — said both §4.3 content clauses were met. Two
// authoritative documents, opposite answers, and the guarded one was right.
// §4.0 stated "12 lessons, ~10,900 characters, ~12 minutes" in a sentence that
// itself ended "count it again rather than trusting this line," and §2.5's
// track table still named the lesson ids abandoned in the 2026-08-14
// renumbering. The lesson is not "the plan needs proofreading" — it is that a
// figure a human maintains rots in the exact place the project most needs it
// true. So the plan's catalogue figures are generated too, and its *arguments*
// (§4.1/§4.2's reasoning about finite content) are deliberately left alone:
// where those cited a count, the count was removed rather than guarded, since
// the cheapest permanent fix for a figure nobody needs is to delete it.
// ═══════════════════════════════════════════════════════════════════════════

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const READINESS = "LAUNCH_READINESS.md";
const PLAN = "LAUNCH_PLAN.md";
const LANGS = ["en", "es", "ko", "zh", "ja"];

// §4.3's Phase-0 content gate, as the plan's own table states it. Kept here so
// the "is it met?" sentence in §4.3 is derived from the catalogue rather than
// from whoever last read the table.
const GATE_LESSONS = 40;
const GATE_MINUTES = 120; // "~2 hours"

const mode = process.argv[2] ?? "";
if (!["", "--check", "--write"].includes(mode)) {
  console.error(`usage: node scripts/refresh-readiness.mjs [--check|--write]`);
  process.exit(2);
}

// ───────────────────────────────────────────────────────────────────────────
// Measure. `lessons.js` holds id/track/minutes/title/subtitle; body text lives
// in the ten `lessonContent.<track>.<lang>.js` files, and `lessonContent.js`
// is their node-only merged view — the one source that can see every language
// at once, which is what a volume measurement needs. Both paths are real
// imports, so a future split breaks this loudly instead of silently.
// `quizData.js` and `glossary.js` join for §1's asset sentence, which counts
// questions and terms rather than lessons.
const [{ lessons }, { lessonContent }, { quizData }, { glossary }] = await Promise.all([
  import("../src/content/lessons.js"),
  import("../src/content/lessonContent.js"),
  import("../src/content/quizData.js"),
  import("../src/content/glossary.js"),
]);

const chars = Object.fromEntries(LANGS.map((l) => [l, 0]));
const tracks = {};
let minutes = 0;
let words = 0;

for (const lesson of lessons) {
  minutes += lesson.minutes || 0;
  (tracks[lesson.track] ||= []).push(lesson.id);
  const content = lessonContent[lesson.id];
  for (const lang of LANGS) {
    chars[lang] += (content?.takeaway?.[lang] || "").length;
    chars[lang] += (content?.thinkAbout?.[lang] || "").length;
    for (const section of content?.sections || []) {
      chars[lang] += (section.body?.[lang] || "").length;
    }
  }
  for (const text of [
    content?.takeaway?.en || "",
    content?.thinkAbout?.en || "",
    ...(content?.sections || []).map((s) => s.body?.en || ""),
  ]) {
    words += (text.match(/\S+/g) || []).length;
  }
}

for (const ids of Object.values(tracks)) ids.sort((a, b) => a - b);

// `quizData` is an array of questions; `glossary` is keyed by term, not an
// array — `glossary.length` is `undefined`, and the floor below caught exactly
// that on the first run of this script. Item 57 records the same shape biting a
// different measurement, which is why the floors are here and not decoration.
const glossaryTerms = Object.keys(glossary).length;

// §2.5 states each track as an id *range* ("1–28 (28)"), which is only honest
// while the ids are contiguous. If a future lesson lands out of order the range
// form silently starts lying, so it is checked below rather than assumed.
const contiguous = (ids) => ids.every((id, i) => i === 0 || id === ids[i - 1] + 1);
const range = (track) => {
  const ids = tracks[track];
  return `${ids[0]}–${ids[ids.length - 1]} (${ids.length})`;
};

// Floors, before anything is printed or written. A generate-and-diff guard is
// only as trustworthy as its generator: if an import silently yielded nothing,
// `--write` would helpfully rewrite the scorecard to read "0 lessons / 0
// English chars" and `--check` would then agree with it forever. Fail on the
// computation, not on the document.
const floors = [
  [lessons.length >= 20, `lesson count ${lessons.length} (expect ≥20)`],
  [minutes >= 50, `minutes ${minutes} (expect ≥50)`],
  [chars.en >= 50_000, `English chars ${chars.en} (expect ≥50,000)`],
  [words >= 8_000, `English words ${words} (expect ≥8,000)`],
  ...LANGS.slice(1).map((l) => [chars[l] > 0, `${l} chars ${chars[l]} (expect >0)`]),
  [Object.keys(tracks).length === 2, `${Object.keys(tracks).length} tracks (expect 2)`],
  [quizData.length >= 20, `quiz questions ${quizData.length} (expect ≥20)`],
  [glossaryTerms >= 10, `glossary terms ${glossaryTerms} (expect ≥10)`],
  // Not a floor on volume but on *shape*: §2.5's range form is unwritable if a
  // track's ids have a hole in them, and writing "1–28 (27)" would be worse
  // than writing nothing.
  ...Object.entries(tracks).map(([t, ids]) => [
    contiguous(ids),
    `track "${t}" ids are not contiguous (${ids.join(", ")}) — LAUNCH_PLAN.md §2.5 states each ` +
      `track as a range, which cannot describe this catalogue. Change §2.5's table to a list and ` +
      `this script's ${"`range()`"} with it, rather than letting the range round over the gap`,
  ]),
];
const broken = floors.filter(([ok]) => !ok).map(([, why]) => why);
if (broken.length) {
  console.error(
    `refresh-readiness: the measurement itself looks wrong, so nothing was compared or written:\n` +
      broken.map((b) => `  - ${b}`).join("\n") +
      `\nCheck that src/content/{lessons,lessonContent,quizData,glossary}.js still export what this ` +
      `script reads before touching ${READINESS} or ${PLAN}.`,
  );
  process.exit(1);
}

// Deterministic, locale-independent thousands separators — the document's own
// format. `toLocaleString` would make this output depend on the runtime's ICU.
const n = (v) => String(v).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
const ratio = (lang) => (chars[lang] / chars.en).toFixed(3);
// The plan writes its volume figures with a leading "~", so they are rounded to
// match. A "~" in front of an exact count reads as false precision, and worse,
// it invites a reader to treat the whole sentence as an estimate someone typed.
const approx = (v, to) => n(Math.round(v / to) * to);

const gateMet = lessons.length >= GATE_LESSONS && minutes >= GATE_MINUTES;

// ───────────────────────────────────────────────────────────────────────────
// The live figures, as the documents state them. Each is a `shape` that
// locates the sentence and an `expected` string that must equal it.
//
// The shape must match even when the numbers are wrong — that is the whole
// mechanism — and a *missing* shape is a failure, not a pass. §11b's note
// applies here too: a check that can be satisfied by deleting the sentence it
// checks is not a check.
const FIGURES = [
  {
    doc: READINESS,
    label: "§4.3 catalogue row",
    shape:
      /\*\*\d+(?:,\d{3})* lessons \/ \d+(?:,\d{3})* English chars \/ \d+(?:,\d{3})* min\*\* — split across \*\*money \(\d+\)\*\* \+ \*\*economy \(\d+\)\*\* tracks/g,
    expected:
      `**${n(lessons.length)} lessons / ${n(chars.en)} English chars / ${n(minutes)} min** — ` +
      `split across **money (${tracks.money.length})** + **economy (${tracks.economy.length})** tracks`,
  },
  {
    doc: READINESS,
    label: "§10.4 translation-volume sentence",
    shape:
      /\*\*es \d+(?:,\d{3})* chars \([\d.]+x of English's \d+(?:,\d{3})*\), ko \d+(?:,\d{3})* \([\d.]+x\), zh \d+(?:,\d{3})* \([\d.]+x\), ja \d+(?:,\d{3})* \([\d.]+x\)\*\*/g,
    expected:
      `**es ${n(chars.es)} chars (${ratio("es")}x of English's ${n(chars.en)}), ` +
      `ko ${n(chars.ko)} (${ratio("ko")}x), zh ${n(chars.zh)} (${ratio("zh")}x), ` +
      `ja ${n(chars.ja)} (${ratio("ja")}x)**`,
  },
  {
    doc: PLAN,
    label: "§1 asset sentence",
    shape:
      /\*\*\d+(?:,\d{3})* sequenced lessons, \d+(?:,\d{3})* quiz questions with explanations, \d+(?:,\d{3})* glossary terms\*\*/g,
    expected:
      `**${n(lessons.length)} sequenced lessons, ${n(quizData.length)} quiz questions with ` +
      `explanations, ${n(glossaryTerms)} glossary terms**`,
  },
  {
    doc: PLAN,
    label: "§2.5 money-track row",
    shape: /`money` \| \d+[–-]\d+ \(\d+\)/g,
    expected: "`money` | " + range("money"),
  },
  {
    doc: PLAN,
    label: "§2.5 economy-track row",
    shape: /`economy` \| \d+[–-]\d+ \(\d+\)/g,
    expected: "`economy` | " + range("economy"),
  },
  {
    doc: PLAN,
    label: "§3.2 first-session progress figure",
    // "bar", not "ring": item 62's F4, decided 2026-08-17. The noun is inside
    // the guarded shape on purpose — this sentence is the one place a *figure*
    // kept a *noun* true-looking while it was wrong, so pinning both is the
    // fix. If a progress ring is ever actually built, this check fails and the
    // plan gets updated in the same change, which is the intended behaviour.
    shape: /progress bar at 1\/\d+(?:,\d{3})*/g,
    expected: `progress bar at 1/${n(lessons.length)}`,
  },
  {
    doc: PLAN,
    label: "§4.0 catalogue-volume sentence",
    shape:
      /\*\*\d+(?:,\d{3})* lessons, ~\d+(?:,\d{3})* characters of English body text, ~\d+(?:,\d{3})* minutes of reading end to end\*\*/g,
    expected:
      `**${n(lessons.length)} lessons, ~${approx(chars.en, 1000)} characters of English body text, ` +
      `~${n(minutes)} minutes of reading end to end**`,
  },
  {
    doc: PLAN,
    label: "§4.0 word-count sentence",
    shape: /roughly \*\*\d+(?:,\d{3})* words\*\*/g,
    expected: `roughly **${approx(words, 100)} words**`,
  },
  {
    doc: PLAN,
    label: "§4.0 asset-table lesson row",
    shape: /\| \d+(?:,\d{3})* lessons \+ quiz \+ glossary \|/g,
    expected: `| ${n(lessons.length)} lessons + quiz + glossary |`,
  },
  {
    // The figure that made this document worth guarding: on 2026-08-17 this
    // sentence said the gate was not close while the generated scorecard said
    // it was met. Deriving the verdict, not just the numbers, is the point.
    doc: PLAN,
    label: "§4.3 Phase-0 content-gate verdict",
    shape: /its first gate is \*\*(?:met|not met)\*\* \(\d+(?:,\d{3})* lessons \/ \d+(?:,\d{3})* min\)/g,
    expected:
      `its first gate is **${gateMet ? "met" : "not met"}** ` +
      `(${n(lessons.length)} lessons / ${n(minutes)} min)`,
  },
];

const DOCS = [...new Set(FIGURES.map((f) => f.doc))];

if (mode === "") {
  console.log(`${lessons.length} lessons, ${chars.en} en chars, ${words} en words, ${minutes} minutes`);
  console.log(
    `tracks: ${Object.entries(tracks).map(([t, ids]) => `${t} ${range(t)}`).join(", ")}`,
  );
  console.log(`quiz questions: ${quizData.length}, glossary terms: ${glossaryTerms}`);
  console.log(
    `chars: ${LANGS.map((l) => `${l} ${chars[l]}${l === "en" ? "" : ` (${ratio(l)}x)`}`).join(", ")}`,
  );
  for (const d of DOCS) {
    console.log(`\nAs ${d} states them:`);
    for (const f of FIGURES.filter((f) => f.doc === d)) console.log(`  ${f.label}: ${f.expected}`);
  }
  console.log(`\nRun with --write to put these into the documents, or --check to compare.`);
  process.exit(0);
}

// ───────────────────────────────────────────────────────────────────────────
// Compare, and for --write, replace. One pass per document, so a failure in
// one never leaves another half-written.
let failures = 0;
let written = 0;

for (const name of DOCS) {
  const path = join(ROOT, name);
  let doc = readFileSync(path, "utf8");
  let dirty = 0;

  for (const { label, shape, expected } of FIGURES.filter((f) => f.doc === name)) {
    const found = doc.match(shape);

    if (!found) {
      failures++;
      console.error(
        `FAIL ${name} ${label}: the sentence this guard reads is not in the file at all.\n` +
          `  expected shape: ${shape.source}\n` +
          `  This is a failure and not a pass on purpose: a generated figure that has been reworded, ` +
          `moved or deleted is exactly the state the guard exists to catch. Restore the sentence — the ` +
          `text it should contain is:\n    ${expected}`,
      );
      continue;
    }

    if (found.length > 1) {
      // A second copy of a derived figure is a second thing that can rot, which
      // is the defect this item removes rather than guards.
      failures++;
      console.error(
        `FAIL ${name} ${label}: stated ${found.length} times. A derived figure belongs in exactly ` +
          `one place; delete the duplicates.\n  ${found.join("\n  ")}`,
      );
      continue;
    }

    if (found[0] === expected) continue;

    if (mode === "--write") {
      doc = doc.replace(shape, expected);
      dirty++;
      written++;
      console.log(`updated ${name} ${label}:\n  was: ${found[0]}\n  now: ${expected}`);
      continue;
    }

    failures++;
    console.error(
      `FAIL ${name} ${label} disagrees with the live content.\n` +
        `  it says:   ${found[0]}\n` +
        `  should be: ${expected}\n` +
        `  Fix with:  npm run readiness -- --write`,
    );
  }

  if (mode === "--write" && dirty) writeFileSync(path, doc);
}

if (mode === "--write") {
  if (!written) console.log(`${DOCS.join(" and ")} already match the live content — nothing to write.`);
  process.exit(failures === 0 ? 0 : 1);
}

if (failures === 0) {
  console.log(
    `  readiness figures: ${lessons.length} lessons / ${n(chars.en)} en chars / ${minutes} min, ` +
      `${FIGURES.length} generated figures across ${DOCS.join(" + ")} agree with the content.`,
  );
}
process.exit(failures === 0 ? 0 : 1);
